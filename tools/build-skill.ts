// Writes the agent skill in skills/mosaic-home-design-system/ from the source of truth: one reference per component
// (catalogue entry, stylesheet, the option and handle types from src, and the gallery's examples), copies
// of docs/getting-started.md and docs/tokens.md, and the component index inside SKILL.md.
// `node tools/build-skill.ts --check` fails when the skill is out of date.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG, GROUPS, WEB_READY } from '../src/catalog.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skill = join(root, 'skills/mosaic-home-design-system');
const check = process.argv.includes('--check');
const GENERATED = '<!-- Generated by tools/build-skill.ts from the source. Do not edit. -->';

const walk = (dir: string, test: (f: string) => boolean): string[] =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p, test) : test(f) ? [p] : [];
  });
const sources = (dir: string): Map<string, string> =>
  new Map(walk(join(root, dir), (f) => /\.tsx?$/.test(f) && !/\.test\.tsx?$/.test(f)).map((p) => [p, readFileSync(p, 'utf8')]));
const WEB = sources('src/web');
const REACT = sources('src/react');

/** The doc comment right before `index`, if any. */
function docBefore(text: string, index: number): string {
  const head = text.slice(0, index).trimEnd();
  if (!head.endsWith('*/')) return '';
  const start = head.lastIndexOf('/**');
  return start < 0 ? '' : `${head.slice(start)}\n`;
}

/** The text of a balanced block starting at the first `open` after `from`. */
function block(text: string, from: number, open = '{', close = '}'): number {
  let depth = 0;
  for (let i = text.indexOf(open, from); i < text.length; i++) {
    if (text[i] === open) depth++;
    else if (text[i] === close && --depth === 0) return i + 1;
  }
  return text.length;
}

/** `export interface Name …` or `export type Name = …;`, with its doc comment. */
function declaration(files: Map<string, string>, name: string): { file: string; text: string } | null {
  for (const [file, text] of files) {
    const m = new RegExp(String.raw`^export (interface|type) ${name}\b[^\n]*`, 'm').exec(text);
    if (!m) continue;
    let end: number;
    if (m[1] === 'interface') end = block(text, m.index);
    else {
      // A type alias ends at the first semicolon outside brackets.
      let depth = 0;
      end = text.length;
      for (let i = m.index; i < text.length; i++) {
        const c = text[i];
        if (c === '{' || c === '(' || c === '[' || c === '<') depth++;
        else if (c === '}' || c === ')' || c === ']' || c === '>') depth--;
        else if (c === ';' && depth <= 0) {
          end = i + 1;
          break;
        }
      }
    }
    return { file, text: `${docBefore(text, m.index)}${text.slice(m.index, end)}` };
  }
  return null;
}

/** The option, prop and handle types worth showing in full. */
const TYPE_NAME = /\b([A-Z]\w*(?:Options|Props|Handle|Labels|Data|Events|Item|Entry))\b/g;

/** A function's signature line, its doc comment and the named types it takes and returns. */
function fn(files: Map<string, string>, name: string): { file: string; doc: string; signature: string; types: string[] } | null {
  for (const [file, text] of files) {
    const m = new RegExp(String.raw`^export function ${name}\b`, 'm').exec(text);
    if (!m) continue;
    const paramsEnd = block(text, m.index, '(', ')');
    const bodyStart = text.indexOf('{', paramsEnd);
    const signature = text.slice(m.index, bodyStart).trim();
    const types = [...new Set([...signature.matchAll(TYPE_NAME)].map((t) => t[1]!))];
    return { file, doc: docBefore(text, m.index).replace(/^\/\*\*\s*|\s*\*\/\s*$/g, '').replace(/^\s*\* ?/gm, '').trim(), signature, types };
  }
  return null;
}

const rel = (file: string): string => relative(root, file).replace(/\\/g, '/');
const imported = (code: string, entry: string): string[] =>
  [...code.matchAll(new RegExp(String.raw`import \{([^}]*)\} from '@mosaic-home/design-system/${entry}'`, 'g'))]
    .flatMap((m) => m[1]!.split(','))
    .map((s) => s.trim())
    .filter((s) => s && !s.startsWith('type '));

function api(files: Map<string, string>, names: string[], dist: (file: string) => string): string {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const name of names) {
    const f = fn(files, name);
    if (!f) continue;
    out.push(`\`${name}\` (types in \`${dist(f.file)}\`)${f.doc ? `: ${f.doc.replace(/\n+/g, ' ')}` : ''}`, '', '```ts', `${f.signature};`);
    // The types it takes and returns, and the ones those build on.
    const queue = [...f.types];
    while (queue.length) {
      const t = queue.shift()!;
      if (seen.has(t)) continue;
      seen.add(t);
      const d = declaration(files, t);
      if (!d) continue;
      out.push('', d.text);
      queue.push(...[...d.text.matchAll(TYPE_NAME)].map((x) => x[1]!).filter((x) => x !== t));
    }
    out.push('```', '');
  }
  return out.join('\n');
}

const example = (kind: 'web' | 'react', id: string): string | null => {
  const p = join(root, 'explorer/examples', kind, `${id}.${kind === 'web' ? 'ts' : 'tsx'}`);
  return existsSync(p) ? readFileSync(p, 'utf8').trimEnd() : null;
};
const distPath = (file: string): string => `dist/${rel(file).replace(/^src\//, '').replace(/\.tsx?$/, '.d.ts')}`;

const files = new Map<string, string>();

// One file per component, so an agent reads only the ones it uses.
for (const e of CATALOG.filter((x) => WEB_READY.has(x.id))) {
  const group = GROUPS.find((g) => g.id === e.group)!;
  const web = example('web', e.id);
  const react = example('react', e.id);
  const parts = [
    GENERATED,
    '',
    `# ${e.name} (\`${e.id}\`)`,
    '',
    e.summary,
    '',
    `Group: ${group.name}. Styles: \`import '@mosaic-home/design-system/css/${group.id}';\` (or \`style.css\`).`,
    '',
  ];
  if (web) {
    const webApi = api(WEB, imported(web, 'web'), distPath);
    if (webApi) parts.push('## Web API', '', webApi);
    parts.push('## Web example', '', '```ts', web, '```', '');
  }
  if (react) {
    const reactApi = api(REACT, imported(react, 'react'), distPath);
    if (reactApi) parts.push('## React API', '', reactApi);
    parts.push('## React example', '', '```tsx', react, '```', '');
  }
  files.set(`references/components/${e.id}.md`, `${parts.join('\n').trimEnd()}\n`);
}

for (const doc of ['getting-started.md', 'tokens.md']) files.set(`references/${doc}`, `${GENERATED}\n\n${readFileSync(join(root, 'docs', doc), 'utf8')}`);

// The component index inside SKILL.md, between its markers.
const index = GROUPS.map((g) => {
  const ids = CATALOG.filter((e) => e.group === g.id && WEB_READY.has(e.id)).map((e) => `[\`${e.id}\`](references/components/${e.id}.md)`);
  return `- **${g.name}** (\`css/${g.id}\`): ${ids.join(', ')}`;
}).join('\n');
const skillMd = join(skill, 'SKILL.md');
const current = readFileSync(skillMd, 'utf8');
const marked = current.replace(/(<!-- components:start -->\n)[\s\S]*?(\n<!-- components:end -->)/, `$1${index}$2`);
files.set('SKILL.md', marked);

let stale = 0;
for (const [path, text] of files) {
  const p = join(skill, path);
  const old = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (old === text) continue;
  stale++;
  if (check) console.error(`skills/mosaic-home-design-system/${path} is out of date`);
  else {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
  }
}
// Reference files for groups that no longer exist.
const refs = join(skill, 'references/components');
if (existsSync(refs))
  for (const f of readdirSync(refs))
    if (!files.has(`references/components/${f}`)) {
      stale++;
      if (check) console.error(`skills/mosaic-home-design-system/references/components/${f} is stale`);
      else rmSync(join(refs, f));
    }
if (check && stale) {
  console.error('Run `npm run skill`.');
  process.exit(1);
}
console.log(check ? 'skill is up to date' : `wrote ${stale} skill file(s)`);
