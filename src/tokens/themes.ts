/** The built-in themes, in display order. */
export const THEMES: readonly Theme[] = [midnight, daylight, nightstand, contrast];

export const DEFAULT_THEME_ID = 'midnight';

export function themeById(id: string): Theme | undefined {
  return THEMES.find((t) => t.id === id);
}

/** A theme with some of its character replaced: the "tune" axes (corners, density, depth, glow...). */
export function withCharacter(theme: Theme, character: Partial<Character>): Theme {
  return { ...theme, character: { ...theme.character, ...character } };
}
